package com.example.javaanalyzer.analysis.plugin.mybatis;

import com.example.javaanalyzer.analysis.AnalysisContext;
import com.example.javaanalyzer.analysis.AnnotationSupport;
import com.example.javaanalyzer.analysis.KnownTypes;
import com.example.javaanalyzer.analysis.ParsedType;
import com.example.javaanalyzer.analysis.StructureExtractor;
import com.example.javaanalyzer.analysis.TypeNameResolver;
import com.example.javaanalyzer.analysis.plugin.AnalyzerPlugin;
import com.example.javaanalyzer.analysis.plugin.mybatis.MapperXmlReader.MapperXml;
import com.example.javaanalyzer.analysis.plugin.mybatis.MapperXmlReader.Statement;
import com.example.javaanalyzer.ir.AnalysisIssue;
import com.example.javaanalyzer.ir.IssueKind;
import com.example.javaanalyzer.ir.IssueSeverity;
import com.example.javaanalyzer.ir.MapperModel;
import com.example.javaanalyzer.ir.MapperStatementModel;
import com.example.javaanalyzer.ir.MethodModel;
import com.example.javaanalyzer.ir.StatementSource;
import com.example.javaanalyzer.ir.TypeRef;
import com.github.javaparser.ast.body.ClassOrInterfaceDeclaration;
import com.github.javaparser.ast.body.MethodDeclaration;
import com.github.javaparser.ast.expr.AnnotationExpr;
import com.github.javaparser.ast.expr.Expression;
import com.github.javaparser.ast.type.ClassOrInterfaceType;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import javax.xml.stream.XMLStreamException;
import org.springframework.stereotype.Component;

/**
 * MyBatis / MyBatis-Plus analyzer (FR-15, shallow): mapper interfaces and their SQL as written. An
 * XML is linked by its namespace and a statement by its id; the SQL is never interpreted.
 *
 * <p>Always supported, because a project can use mapper XML without importing any MyBatis type.
 *
 * <p>Known limitations: methods generated by a base interface are not inferred; interfaces of other
 * base mappers, such as tk.mybatis, are found only through {@code @Mapper} or an XML namespace;
 * {@code <include>} is not expanded; a file using a custom XML entity is reported, not read.
 */
@Component
public class MyBatisPlugin implements AnalyzerPlugin {

  private static final List<String> XML_ROOTS = List.of("src/main/resources", "src/main/java");
  private static final String XML_EXTENSION = ".xml";
  private static final String ANNOTATIONS = "org.apache.ibatis.annotations.";
  private static final String MAPPER_ANNOTATION = ANNOTATIONS + "Mapper";
  private static final Set<String> BASE_MAPPERS =
      Set.of("com.baomidou.mybatisplus.core.mapper.BaseMapper");

  /** Annotation simple name to the statement tag it stands for. */
  private static final Map<String, String> SQL_ANNOTATIONS =
      Map.of("Select", "select", "Insert", "insert", "Update", "update", "Delete", "delete");

  private static final Map<String, String> PROVIDER_ANNOTATIONS =
      Map.of(
          "SelectProvider", "select",
          "InsertProvider", "insert",
          "UpdateProvider", "update",
          "DeleteProvider", "delete");

  private record XmlMapper(List<String> files, List<Statement> statements) {}

  @Override
  public String name() {
    return "MyBatis";
  }

  @Override
  public boolean supports(AnalysisContext context) {
    return true;
  }

  @Override
  public void analyze(AnalysisContext context) {
    context.qualifyAnnotations(recognizedAnnotations());
    Map<String, XmlMapper> xmlByNamespace = readMapperXml(context);
    Map<String, ParsedType> parsedByName = new HashMap<>();
    context.parsedTypes().forEach(parsed -> parsedByName.put(parsed.qualifiedName(), parsed));

    for (ParsedType parsed : context.parsedTypes()) {
      if (parsed.declaration() instanceof ClassOrInterfaceDeclaration declaration
          && declaration.isInterface()) {
        XmlMapper xml = xmlByNamespace.remove(parsed.qualifiedName());
        TypeRef baseType =
            baseMapperOf(declaration, parsed.resolver(), parsedByName, new HashSet<>());
        List<MapperStatementModel> annotated = annotationStatements(declaration, parsed.resolver());
        if (xml != null
            || baseType != null
            || !annotated.isEmpty()
            || AnnotationSupport.has(declaration, parsed.resolver(), MAPPER_ANNOTATION)) {
          context.addMapper(mapperOf(context, parsed, xml, baseType, annotated));
        }
      }
    }
    xmlByNamespace.forEach(
        (namespace, xml) ->
            context.addMapper(
                new MapperModel(
                    null,
                    namespace,
                    xml.files(),
                    null,
                    xml.statements().stream().map(s -> xmlStatement(s, Set.of())).toList())));
  }

  private static List<String> recognizedAnnotations() {
    List<String> names = new ArrayList<>(List.of(MAPPER_ANNOTATION));
    SQL_ANNOTATIONS.keySet().forEach(name -> names.add(ANNOTATIONS + name));
    PROVIDER_ANNOTATIONS.keySet().forEach(name -> names.add(ANNOTATIONS + name));
    return names;
  }

  private static MapperModel mapperOf(
      AnalysisContext context,
      ParsedType parsed,
      XmlMapper xml,
      TypeRef baseType,
      List<MapperStatementModel> annotated) {
    Set<String> methodNames =
        context.type(parsed.qualifiedName()).methods().stream()
            .map(MethodModel::name)
            .collect(Collectors.toSet());
    List<MapperStatementModel> statements = new ArrayList<>();
    if (xml != null) {
      xml.statements().forEach(statement -> statements.add(xmlStatement(statement, methodNames)));
    }
    statements.addAll(annotated);
    return new MapperModel(
        parsed.qualifiedName(),
        xml == null ? null : parsed.qualifiedName(),
        xml == null ? List.of() : xml.files(),
        baseType,
        statements);
  }

  private static MapperStatementModel xmlStatement(Statement statement, Set<String> methodNames) {
    return new MapperStatementModel(
        statement.tag(),
        statement.id(),
        statement.sql(),
        true,
        StatementSource.XML,
        methodNames.contains(statement.id()) ? statement.id() : null);
  }

  /** The base mapper as written, found directly or through project interfaces. */
  private static TypeRef baseMapperOf(
      ClassOrInterfaceDeclaration declaration,
      TypeNameResolver resolver,
      Map<String, ParsedType> parsedByName,
      Set<String> visited) {
    for (ClassOrInterfaceType extended : declaration.getExtendedTypes()) {
      TypeRef type = StructureExtractor.typeRef(extended, resolver);
      Optional<String> name = KnownTypes.match(type, resolver, BASE_MAPPERS);
      if (name.isPresent()) {
        return new TypeRef(type.text(), name.get(), type.typeArguments());
      }
      ParsedType parent = type.resolved() ? parsedByName.get(type.qualifiedName()) : null;
      if (parent != null
          && visited.add(parent.qualifiedName())
          && parent.declaration() instanceof ClassOrInterfaceDeclaration parentDeclaration) {
        TypeRef inherited =
            baseMapperOf(parentDeclaration, parent.resolver(), parsedByName, visited);
        if (inherited != null) {
          return inherited;
        }
      }
    }
    return null;
  }

  private static List<MapperStatementModel> annotationStatements(
      ClassOrInterfaceDeclaration declaration, TypeNameResolver resolver) {
    List<MapperStatementModel> statements = new ArrayList<>();
    for (MethodDeclaration method : declaration.getMethods()) {
      SQL_ANNOTATIONS.forEach(
          (name, tag) ->
              AnnotationSupport.find(method, resolver, ANNOTATIONS + name)
                  .ifPresent(a -> statements.add(sqlAnnotationStatement(a, tag, method))));
      PROVIDER_ANNOTATIONS.forEach(
          (name, tag) ->
              AnnotationSupport.find(method, resolver, ANNOTATIONS + name)
                  .ifPresent(
                      a -> statements.add(annotationStatement(tag, method, a.toString(), false))));
    }
    return statements;
  }

  private static MapperStatementModel sqlAnnotationStatement(
      AnnotationExpr annotation, String tag, MethodDeclaration method) {
    List<Expression> values =
        AnnotationSupport.attribute(annotation, "value")
            .map(AnnotationSupport::values)
            .orElse(List.of());
    boolean resolved =
        values.stream().allMatch(value -> AnnotationSupport.stringValue(value).isPresent());
    String sql =
        values.stream()
            .map(value -> AnnotationSupport.stringValue(value).orElseGet(value::toString))
            .collect(Collectors.joining("\n"));
    return annotationStatement(tag, method, sql, resolved);
  }

  private static MapperStatementModel annotationStatement(
      String tag, MethodDeclaration method, String sql, boolean resolved) {
    String methodName = method.getNameAsString();
    return new MapperStatementModel(
        tag, methodName, sql, resolved, StatementSource.ANNOTATION, methodName);
  }

  private static Map<String, XmlMapper> readMapperXml(AnalysisContext context) {
    Map<String, XmlMapper> xmlByNamespace = new LinkedHashMap<>();
    for (Path file : xmlFiles(context.projectRoot())) {
      String relativePath = context.projectRoot().relativize(file).toString().replace('\\', '/');
      try {
        Optional<MapperXml> xml = MapperXmlReader.read(Files.readAllBytes(file));
        if (xml.isPresent()) {
          addMapperXml(context, xmlByNamespace, relativePath, xml.get());
        }
      } catch (XMLStreamException e) {
        context.addIssue(xmlIssue(relativePath, lineOf(e), "XMLとして解析できないため、このファイルをスキップしました。"));
      } catch (IOException e) {
        throw new UncheckedIOException("Failed to read " + file, e);
      }
    }
    return xmlByNamespace;
  }

  private static void addMapperXml(
      AnalysisContext context,
      Map<String, XmlMapper> xmlByNamespace,
      String relativePath,
      MapperXml xml) {
    if (xml.namespace() == null) {
      context.addIssue(xmlIssue(relativePath, null, "mapper要素にnamespaceがないため、対応付けできません。"));
      return;
    }
    XmlMapper mapper =
        xmlByNamespace.computeIfAbsent(
            xml.namespace(), namespace -> new XmlMapper(new ArrayList<>(), new ArrayList<>()));
    mapper.files().add(relativePath);
    mapper.statements().addAll(xml.statements());
  }

  private static Integer lineOf(XMLStreamException exception) {
    return exception.getLocation() != null && exception.getLocation().getLineNumber() > 0
        ? exception.getLocation().getLineNumber()
        : null;
  }

  private static AnalysisIssue xmlIssue(String file, Integer line, String message) {
    return new AnalysisIssue(IssueKind.XML_PARSE_ERROR, IssueSeverity.WARNING, file, line, message);
  }

  private static List<Path> xmlFiles(Path projectRoot) {
    List<Path> files = new ArrayList<>();
    for (String root : XML_ROOTS) {
      Path directory = projectRoot.resolve(root);
      if (Files.isDirectory(directory)) {
        try (Stream<Path> paths = Files.walk(directory)) {
          paths.filter(MyBatisPlugin::isXmlFile).sorted().forEach(files::add);
        } catch (IOException e) {
          throw new UncheckedIOException("Failed to list XML files under " + directory, e);
        }
      }
    }
    return files;
  }

  private static boolean isXmlFile(Path path) {
    return Files.isRegularFile(path)
        && path.getFileName().toString().toLowerCase(Locale.ROOT).endsWith(XML_EXTENSION);
  }
}
